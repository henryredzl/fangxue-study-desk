function readCards(rows) {
  return rows.trim().split('\n').map(row => {
    const [ask, answer, error, method] = row.split('|');
    if (!ask || !answer || !error || !method || answer === error) throw new Error(`Invalid task card: ${row}`);
    return {ask, answer, error, method};
  });
}

function method(title, text) {
  return {title, text};
}

function compare(card) {
  return `把“${card.answer}”放回原题，逐项对照条件。再用“${card.error}”试一次，找出哪一处对不上。`;
}

function simple(card, ask, seed, type = 'pick') {
  const {answer, error, visual, answerFormat} = card;
  const choices = seed % 2 ? [error,answer] : [answer,error];
  const accepted = card.acceptEquivalent
    ? [...new Set([answer,String(Number(answer)),answer.includes('.') ? answer+'0' : answer+'.0'])]
    : /^-?\d+\.\d$/.test(answer)
    ? [answer,...(answer.endsWith('.0') ? [String(Number(answer))] : []),answer+'0']
    : [answer];
  return {
    ask, type, ...(type === 'fill' ? {answer:[...accepted,...(card.aliases || [])]} : {choices,answer:choices.indexOf(answer)}),
    ...(visual ? {visual} : {}),
    ...(type === 'fill' && answerFormat ? {answerFormat} : {}),
    methods:[method(card.check ? '一种解法' : '找关键线索',card.method),
      method(card.check ? '另一种解法' : '回到原题检验',card.check || compare(card))]
  };
}

function cardPair(first, second, ask, seed) {
  const key = (card, label) => `${label}：${card.answer}`;
  const result = [key(first,'甲'),key(second,'乙')];
  const choices = [result[0],`甲：${first.error}`,result[1],`乙：${second.error}`];
  if (seed % 2) choices.reverse();
  return {
    ask:`${ask}\n甲　${first.ask}\n乙　${second.ask}`,
    type:'multi', choices, answer:result.map(value=>choices.indexOf(value)),
    methods:[
      method('分别找线索',`甲：${first.method} 乙：${second.method}`),
      method('填回去检查',`把甲的两个答案分别代回甲卡，把乙的两个答案代回乙卡。保留符合条件的：“${result.join('”、“')}”。`)
    ]
  };
}

function revisePair(first, second, swap) {
  const [left,right] = swap ? [second,first] : [first,second];
  const presented = swap ? [left.answer,right.error] : [left.error,right.answer];
  return {
    ask:`两张卡只有一张填错了。哪条修改合适？\n甲　${left.ask} 卡上写：${presented[0]}\n乙　${right.ask} 卡上写：${presented[1]}`,
    type:'pick', choices:[`甲改成：${swap ? left.error : left.answer}`,`乙改成：${swap ? right.answer : right.error}`],
    answer: swap ? 1 : 0,
    methods:[
      method('逐张判断',`甲：${left.method} 乙：${right.method}`),
      method('检查修改的结果',`把两个修改方案分别放回原题，只保留让两张卡同时符合题意的一项。`)
    ]
  };
}

function sequence(parts, scene, english) {
  const [first,second,third] = parts;
  return {
    ask: english
      ? `${scene}上，按能实际完成的先后，把三条英文指令排好。`
      : `${scene}要把三条打乱的记录排好。按事情发生的先后排序。`,
    type:'order', choices:[second,third,first], answer:[2,0,1],
    methods:[
      method('先找起点',`“${first}”提供接下来要用的条件，先把它放在最前面。`),
      method('从结果倒推',`“${third}”是最后一步。想做成这一步，前面要先有“${second}”。`)
    ]
  };
}

function openQuestion(item, scene, english) {
  const [task, answer, checklist] = item;
  return {
    ask:`${scene}小任务。\n${task}`,
    type:'write', answer,
    methods:[
      method(english ? '选词再补全句子' : '先列要点再落笔',`围绕任务列出需要写的内容。检查：${checklist}。`),
      method(english ? '读出来再检查' : '读给同伴听再修改',
        `先试着用自己的话${english?'说':'讲'}一遍，把听者需要的内容补完整。把写好的答案和示例对照，看看哪里可以写得更清楚。`)
    ]
  };
}

function languageQuestion(id, cards, city, angle, slot, scene, english) {
  const first = cards[(city + angle + slot * 2) % cards.length];
  const second = cards[(city + angle + 1 + slot * 2) % cards.length];
  const seed = city + angle + slot;
  if (angle === 0) {
    return slot ? cardPair(first,second,'分别想一想两张卡，选出两张卡的正确答案。',seed)
      : simple(first,first.ask,seed);
  }
  if (angle === 1) {
    return slot ? revisePair(first,second,city % 2 === 1)
      : simple(first,`${first.ask}\n有同学填“${first.error}”。重新判断，选出你认为正确的一项。`,seed);
  }
  if (angle === 2) {
    if (slot && sequenceCards[id]) return sequence(sequenceCards[id][city],scene,english);
    if (!slot) return cardPair(first,second,`${scene}收到了两条材料。逐条阅读，替每条材料选一个正确结论。`,seed);
    return simple(first,`资料袋里有一张记录卡：\n${first.ask}\n从卡上的关键词或上下文找依据，再作答。`,seed);
  }
  if (slot && writingCards[id]) return openQuestion(writingCards[id][city],scene,english);
  return slot ? cardPair(first,second,`你在${scene}帮忙核对两张展签。按两张展签的要求分别确定该写什么。`,seed)
    : simple(first,`${scene}请你完成一张任务卡。\n${first.ask}`,seed);
}

function mathQuestion(makeCase, city, angle, slot, scene) {
  const raw = makeCase(city * 8 + angle * 2 + slot);
  const ask = [
    raw.ask,
    `${raw.ask}\n有人答“${raw.error}”。请检查并给出正确结果。`,
    `${scene}的${raw.visual ? '图示' : '记录卡'}\n${raw.ask}`,
    `${scene}小任务。\n${raw.ask}`
  ][angle];
  return simple(raw,ask,city + angle + slot,slot ? 'fill' : 'pick');
}

const cityPracticeBank = (() => {
  const lookup = {...languageCards,...fourthChinese,...fifthLanguage.cn,...englishCards,...fourthEnglish,...fifthLanguage.en,...mathCards,...fourthShapes};
  const entries = Object.entries(lookup).map(([id,rows])=>[id,readCards(rows)]);
  const allMath = {...mathCases,...fourthMath,...fifthMath};
  const all = [...entries,...Object.keys(allMath).map(id=>[id,null])];
  return Object.fromEntries(all.map(([id,cards]) => {
    const has = (source) => Object.prototype.hasOwnProperty.call(source,id);
    const english = has(englishCards) || has(fourthEnglish) || has(fifthLanguage.en);
    const subjectIndex = english ? 2 : has(languageCards) || has(fourthChinese) || has(fifthLanguage.cn) ? 0 : 1;
    const questions = cityNames.flatMap((city,cityIndex)=>[0,1,2,3].flatMap(angle=>[0,1].map(slot=>{
      const scene = scenes[cityIndex][subjectIndex];
      const content = cards ? languageQuestion(id,cards,cityIndex,angle,slot,scene,english)
        : mathQuestion(allMath[id],cityIndex,angle,slot,scene);
      return {
        id:`${id}-city-${cityIndex + 1}-${angle + 1}-${slot + 1}`,
        city, angle, ...content
      };
    })));
    return [id,questions];
  }));
})();

if (typeof module === 'object') module.exports = cityPracticeBank;
