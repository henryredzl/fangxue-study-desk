const groupSize = 8;
const batch = make => Array.from({length:groupSize},(_,i)=>make(i));
const group = (name,questions) => [name,questions];
function drill(book,id,title,category,lesson,groups) {
  assert.ok(groups.every(([,questions])=>questions.length===groupSize),id);
  return {id:`${book}-calc-${id}`,book,title,unit:category,lesson,drill:{size:groupSize,category,sets:groups.map(([name])=>name)},questions:groups.flatMap(([,questions])=>questions)};
}

function sum(a,b,method) {
  const result = a+b;
  let explanation = `${a} 和 ${b} 合起来是 ${result}。`;
  let hint = '可以从第一个数接着往后数。';
  if (method === 'make-ten') {
    const rest = b - (10-a);
    explanation = `从 ${b} 里分出 ${10-a} 给 ${a}，先凑成 10。10＋${rest}＝${result}。`;
    hint = `想想 ${a} 再加几等于 10。`;
  } else if (method === 'column') {
    explanation = `${a}＋${b}＝${result}。数位对齐，从个位算，每一位满十就向前一位进 1。`;
    hint = `先算两个个位：${a % 10}＋${b % 10}。`;
  }
  return fill(`${a} ＋ ${b} =（　）`,result,explanation,{hint});
}

function difference(a,b,method) {
  const result = a-b;
  let explanation = `从 ${a} 去掉 ${b}，还剩 ${result}。`;
  let hint = '可以从第一个数倒着数。';
  if (method === 'break-ten') {
    explanation = `先算 10−${b}＝${10-b}，再加 ${a-10}，得到 ${result}。`;
    hint = `先把 ${a} 看成 10 和 ${a-10}。`;
  } else if (method === 'column') {
    explanation = `${a}−${b}＝${result}。低位不够减时向前一位借 1。用 ${result}＋${b}＝${a} 验算。`;
    hint = '数位对齐，先看个位够不够减。';
  }
  return fill(`${a} − ${b} =（　）`,result,explanation,{hint});
}

function expressionGroup(name,pairs,operation,method) {
  return group(name,pairs.map(([a,b])=>operation(a,b,method)));
}

function tableFact(a,b,division = false) {
  const product = a*b;
  return division
    ? fill(`${product} ÷ ${a} =（　）`,b,`${a}×${b}＝${product}，所以 ${product}÷${a}＝${b}。`,{hint:`想 ${a} 乘几等于 ${product}。`})
    : fill(`${a} × ${b} =（　）`,product,`${b} 个 ${a} 相加，得到 ${product}。`,{hint:'想一想对应的乘法口诀。'});
}

