const books = ['g1a','g1b','g2a','g2b'];
const cities = ['北京','上海','广州','深圳'];
function unitsFor(book,topics,category,cityOffset) {
  return topics.map((entry,index)=>{
    const application = entry.questions[3];
    const questions = [...entry.questions.slice(0,3),{...application,city:cities[(index+cityOffset)%4]}];
    return {...entry,id:`${book}-${entry.id}`,book,unit:category,questions};
  });
}

const additions = {cn:[],math:[],en:[]};
for (const book of books) {
  additions.cn.push(...unitsFor(book,chinese[book],'字词与阅读',0));
  additions.math.push(...unitsFor(book,mathematics[book],'数与图形',2),...computations[book]);
  additions.en.push(...unitsFor(book,english[book],'英语启蒙',0));
}

const transcript = Object.fromEntries(additions.en.flatMap(item=>item.questions.flatMap((q,index)=>q.audio?[[`${item.id}-${index+1}`,q.audio]]:[])));
if (process.argv[2] === '--transcripts') {
  console.log(JSON.stringify(transcript));
  process.exit(0);
}

const htmlPath = path.join(__dirname,'..','index.html');
const html = fs.readFileSync(htmlPath,'utf8');
const region = /(<script id="question-bank" type="application\/json">)[\s\S]*?(<\/script>)/;
const match = html.match(region);
assert.ok(match,'Question bank not found');
const bank = JSON.parse(match[0].slice(match[1].length,-match[2].length));
for (const [subject,list] of Object.entries(additions)) bank[subject] = [...bank[subject].filter(entry=>!books.includes(entry.book)),...list];
for (const book of books) {
  const topics = Object.values(additions).flat().filter(item=>item.book===book);
  const practice = topics.filter(item=>item.drill).flatMap(item=>item.questions.map(q=>q.ask));
  assert.equal(new Set(practice).size,practice.length,`Duplicate calculations for ${book}`);
  assert.ok(topics.every(item=>item.drill || item.questions.length===4),book);
}
const topics = Object.values(bank).flat();
assert.equal(new Set(topics.map(item=>item.id)).size,topics.length,'Duplicate topic ID');
const formatted = JSON.stringify(bank,null,2).replaceAll('<','\\u003c');
let output = html.replace(region,(_,start,end)=>`${start}\n${formatted}\n${end}`);
if (process.argv[2]) {
  const tracks = JSON.parse(fs.readFileSync(process.argv[2],'utf8').replace(/^\uFEFF/,''));
  assert.deepEqual(Object.keys(tracks).sort(),Object.keys(transcript).sort(),'Missing or unexpected early-grade audio');
  const audio = /const audioTracks = (\{[^\r\n]*\});/;
  assert.ok(output.match(audio),'Audio track list not found');
  output = output.replace(audio,(_,existing)=>`const audioTracks = ${JSON.stringify({...JSON.parse(existing),...tracks})};`);
}
if (output !== html) fs.writeFileSync(htmlPath,output);
